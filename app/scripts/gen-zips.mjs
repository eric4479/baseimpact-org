import fs from 'node:fs';
import { createRequire } from 'node:module';

// `zipcodes` is CommonJS; this file is ESM (package.json has "type": "module").
const require = createRequire(import.meta.url);
const z = require('zipcodes');

const rows = [];
for (const [zip, info] of Object.entries(z.codes)) {
  if (info.state !== 'FL') continue;
  rows.push([zip, info.latitude, info.longitude, info.city || '']);
}
rows.sort((a, b) => a[0].localeCompare(b[0]));

const body = rows
  .map(([zip, lat, lng, city]) => `  '${zip}': [${lat}, ${lng}, '${city.replace(/'/g, "\\'")}'],`)
  .join('\n');

const out = `/**
 * Florida ZIP code centroids — generated from the \`zipcodes\` package (dev dependency).
 * Regenerate with: node scripts/gen-zips.mjs
 *
 * Format: zip -> [latitude, longitude, city]
 *
 * Used ONLY for client-side distance sorting. A ZIP is entered by the visitor, resolved to a
 * centroid in the browser, and never sent to or stored on a server. See RISKS_AND_RECOMMENDATIONS.md R3.
 */
export type ZipCentroid = [lat: number, lng: number, city: string];

export const FL_ZIPS: Record<string, ZipCentroid> = {
${body}
};

export const FL_ZIP_COUNT = ${rows.length};
`;

fs.writeFileSync('src/data/fl-zips.ts', out);
console.log('wrote src/data/fl-zips.ts');
console.log('FL zips:', rows.length);
console.log('bytes:', fs.statSync('src/data/fl-zips.ts').size);
console.log('32780:', JSON.stringify(rows.find((r) => r[0] === '32780')));
console.log('32801 (Orlando):', JSON.stringify(rows.find((r) => r[0] === '32801')));
console.log('32114 (Daytona):', JSON.stringify(rows.find((r) => r[0] === '32114')));

// ── Regional subset, shipped to the browser for ZIP → centroid lookup ──────────
// Bounding box covering Brevard, Volusia, Indian River, Orange and Flagler.
// Compact [lat,lng] pairs only — ~8KB raw, ~2KB gzipped. No city names needed client-side.
const BOX = { latMin: 27.5, latMax: 29.75, lngMin: -81.75, lngMax: -80.25 };

const regional = {};
for (const [zip, info] of Object.entries(z.codes)) {
  if (info.state !== 'FL') continue;
  const { latitude: lat, longitude: lng } = info;
  if (lat >= BOX.latMin && lat <= BOX.latMax && lng >= BOX.lngMin && lng <= BOX.lngMax) {
    regional[zip] = [lat, lng];
  }
}

const regionalOut = `/**
 * Regional ZIP centroids for client-side distance sorting.
 * Generated by scripts/gen-zips.mjs — do not edit by hand.
 *
 * Covers the service area: Brevard, Volusia, Indian River, Orange and Flagler counties.
 * Resolved IN THE BROWSER only. A visitor's ZIP is never transmitted or stored
 * (see RISKS_AND_RECOMMENDATIONS.md R3).
 */
export type LatLng = [lat: number, lng: number];

export const REGION_ZIPS: Record<string, LatLng> = ${JSON.stringify(regional)};

export const REGION_ZIP_COUNT = ${Object.keys(regional).length};
`;

fs.writeFileSync('src/data/region-zips.ts', regionalOut);
console.log();
console.log('wrote src/data/region-zips.ts');
console.log('regional zips:', Object.keys(regional).length);
console.log('bytes:', fs.statSync('src/data/region-zips.ts').size);

// ── City centroids, for records that have a city but no street address ─────────
// Approximate by design: a city centroid is NOT a street address. It gives a usable
// "roughly how far" signal for a resource we haven't fully verified yet.
const cityAgg = new Map();
for (const [zip, info] of Object.entries(z.codes)) {
  if (info.state !== 'FL') continue;
  const { latitude: lat, longitude: lng, city } = info;
  if (lat < BOX.latMin || lat > BOX.latMax || lng < BOX.lngMin || lng > BOX.lngMax) continue;
  if (!city) continue;
  const key = city.trim();
  const acc = cityAgg.get(key) || { lat: 0, lng: 0, n: 0 };
  acc.lat += lat;
  acc.lng += lng;
  acc.n += 1;
  cityAgg.set(key, acc);
}

const cities = {};
for (const [name, acc] of cityAgg) {
  cities[name] = [
    Number((acc.lat / acc.n).toFixed(4)),
    Number((acc.lng / acc.n).toFixed(4)),
  ];
}

const citiesOut = `/**
 * City centroids for the service area — generated by scripts/gen-zips.mjs.
 *
 * APPROXIMATE. Used only when a resource has a city but no verified street address,
 * so distance sorting still works before full verification. A city centroid is not a
 * street address and the UI must not present it as one.
 */
export const REGION_CITIES: Record<string, LatLng> = ${JSON.stringify(cities)};

export const REGION_CITY_COUNT = ${Object.keys(cities).length};
`;

fs.writeFileSync('src/data/region-cities.ts', citiesOut);
console.log();
console.log('wrote src/data/region-cities.ts');
console.log('cities:', Object.keys(cities).length);
console.log('Titusville:', JSON.stringify(cities['Titusville']));
console.log('Orlando   :', JSON.stringify(cities['Orlando']));
console.log('Daytona Beach:', JSON.stringify(cities['Daytona Beach']));
console.log('Palm Coast:', JSON.stringify(cities['Palm Coast']));
